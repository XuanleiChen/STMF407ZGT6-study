//假设我要显示5(也就是n=5)
//那么我要的数据就是0x6D
//也就是zhenzhi[5]
//0x6D的二进制就是 0110 1101
//PC7(控制小数点) 输出低电平
//PC6(控制g) 输出低电平
//PC5(控制f) 输出低电平
//PC4(控制e) 输出低电平
//PC3(控制d) 输出低电平
//PC2(控制c) 输出低电平
//PC1(控制b) 输出低电平
//PC0(控制a) 输出低电平

//定义一个uint8_t类型数组，把0~9ABCEF共16个显示符号的真值遍历出来
uint8_t zhenzhi[16]={0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F,0x77,0x7C,0x39,0x5E,0x79,0x71};
void Display_Number(uint8_t n,bool Dot)
{
  uint8_t temp=0x01;  //0000 0001
  for (uint8_t i=0;i<8;i++) {
      if (Dot)
      HAL_GPIO_WritePin(GPIOC,(GPIO_PIN_0<<i),((zhenzhi[n] | 0x80 )& (temp<<i))? 1 : 0);
    else
      HAL_GPIO_WritePin(GPIOC,(GPIO_PIN_0<<i),(zhenzhi[n] & (temp<<i))? 1 : 0);
  }


}
