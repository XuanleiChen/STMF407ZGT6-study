void Display_ShowString(u16 x, u16 y, const char *p, u16 fc, u16 bc, u8 sizey, u8 mode)
{         
	while(*p!='\0')
	{       
		Display_ShowCharacter(x,y,*p,fc,bc,sizey,mode);
		x+=sizey/2;
		p++;
	}  
}
/******************************************************************************
      函数说明：显示数字
      入口数据：m底数，n指数
      返回值：  无
******************************************************************************/
u32 Display_Pow(u8 m,u8 n)
{
	u32 result=1;	 
	while(n--)result*=m;
	return result;
}
/******************************************************************************
      函数说明：显示整数变量
      入口数据：x,y显示坐标
                num 要显示整数变量
                len 要显示的位数
                fc 字的颜色
                bc 字的背景色
                sizey 字号
      返回值：  无
******************************************************************************/
void Display_ShowInteger(u16 x, u16 y, u16 num, u8 len, u16 fc, u16 bc, u8 sizey)
{         	
	u8 t,temp;
	u8 enshow=0;
	u8 sizex=sizey/2;
	for(t=0;t<len;t++)
	{
		temp=(num/Display_Pow(10,len-t-1))%10;
		if(enshow==0&&t<(len-1))
		{
			if(temp==0)
			{
				Display_ShowCharacter(x+t*sizex,y,' ',fc,bc,sizey,0);
				continue;
			}else enshow=1; 
		 	 
		}
	 	Display_ShowCharacter(x+t*sizex,y,temp+48,fc,bc,sizey,0);
	}
}
/******************************************************************************
      函数说明：显示两位小数变量
      入口数据：x,y显示坐标
                num 要显示小数变量
                len 要显示的位数
                fc 字的颜色
                bc 字的背景色
                sizey 字号
      返回值：  无
******************************************************************************/
void Display_ShowFloat(u16 x, u16 y, float num, u8 len, u16 fc, u16 bc, u8 sizey)
{         	
	u8 t,temp,sizex;
	u16 num1;
	sizex=sizey/2;
	num1=num*100;
	for(t=0;t<len;t++)
	{
		temp=(num1/Display_Pow(10,len-t-1))%10;
		if(t==(len-2))
		{
			Display_ShowCharacter(x+(len-2)*sizex,y,'.',fc,bc,sizey,0);
			t++;
			len+=1;
		}
	 	Display_ShowCharacter(x+t*sizex,y,temp+48,fc,bc,sizey,0);
	}
}
/******************************************************************************
      函数说明：显示图片
      入口数据：x,y起点坐标
                length 图片长度
                width  图片宽度
                pic[]  图片数组    
      返回值：  无
******************************************************************************/
void Display_ShowPicture(u16 x, u16 y, u16 height, u16 width, const u8 pic[])
{
	u16 i,j;
	u32 k=0;
	Display_SetAddress(x,y,x+height-1,y+width-1);
	for(i=0;i<height;i++)
	{
		for(j=0;j<width;j++)
		{
			Display_Write1ByteData(pic[k*2]);
			Display_Write1ByteData(pic[k*2+1]);
			k++;
		}
	}
}
